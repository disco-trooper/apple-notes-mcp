#!/usr/bin/env bun
/**
 * Setup wizard for apple-notes-mcp
 *
 * Interactive CLI for configuring:
 * - Embedding provider (Local HuggingFace / OpenRouter)
 * - API keys
 * - Read-only mode
 * - Auto-indexing settings
 * - Claude Code integration
 */

import * as p from "@clack/prompts";
import * as dotenv from "dotenv";
import * as fs from "node:fs";
import {
  getEnvPath,
  ensureConfigDir,
  hasLegacyConfig,
  getLegacyEnvPath,
  hasConfig,
  isNpmInstall,
} from "./config/paths.js";
import {
  getClaudeConfigEntry,
  writeClaudeConfig,
  getExistingInstallMethod,
} from "./config/claude.js";
import { checkBunRuntime } from "./utils/runtime.js";
import { parseFlag } from "./config/env.js";
import { DEFAULT_OPENROUTER_MODEL } from "./config/constants.js";

// Paths
const ENV_FILE = getEnvPath();

interface Config {
  provider: "local" | "openrouter";
  openrouterApiKey?: string;
  embeddingModel?: string;
  embeddingDims?: number;
  readonlyMode: boolean;
  autoIndex: "none" | "on-search" | "ttl";
  indexTtl?: number;
  debug: boolean;
}

/**
 * Read existing .env file if it exists (same parser as the server).
 */
function readExistingEnv(): Record<string, string> {
  if (!fs.existsSync(ENV_FILE)) {
    return {};
  }
  return dotenv.parse(fs.readFileSync(ENV_FILE, "utf-8"));
}

/**
 * Format one KEY=value line so dotenv.parse reads the value back verbatim.
 */
function formatEnvLine(key: string, value: string): string {
  if (/^[\w./:@+-]*$/.test(value)) return `${key}=${value}`;
  if (!value.includes("'")) return `${key}='${value}'`;
  if (!value.includes('"')) return `${key}="${value}"`;
  return `${key}=\`${value}\``;
}

/**
 * Write configuration to .env (mode 0600: it may hold the API key).
 * Wizard-owned keys are replaced (or removed when unset); all other existing
 * keys are kept.
 */
function writeEnvFile(config: Config, existing: Record<string, string>): void {
  ensureConfigDir();

  // Keys the wizard owns; every other key in .env is preserved as-is
  const owned: Record<string, string | undefined> = {
    OPENROUTER_API_KEY: config.provider === "openrouter" ? config.openrouterApiKey : undefined,
    EMBEDDING_MODEL: config.embeddingModel,
    EMBEDDING_DIMS: config.embeddingDims?.toString(),
    READONLY_MODE: config.readonlyMode ? "true" : undefined,
    INDEX_TTL: config.autoIndex === "ttl" ? config.indexTtl?.toString() : undefined,
    DEBUG: config.debug ? "true" : undefined,
  };

  const lines: string[] = [
    "# apple-notes-mcp configuration",
    "# Generated by setup wizard",
    config.provider === "openrouter"
      ? "# Embedding provider: OpenRouter"
      : "# Embedding provider: Local HuggingFace (no OPENROUTER_API_KEY)",
    "",
  ];
  for (const [key, value] of Object.entries(owned)) {
    if (value !== undefined) lines.push(formatEnvLine(key, value));
  }

  const others = Object.entries(existing).filter(([key]) => !(key in owned));
  if (others.length > 0) {
    lines.push("", "# Other settings");
    for (const [key, value] of others) lines.push(formatEnvLine(key, value));
  }

  fs.writeFileSync(ENV_FILE, lines.join("\n") + "\n", { mode: 0o600 });
  // `mode` only applies when the file is created
  fs.chmodSync(ENV_FILE, 0o600);
}

/**
 * Add MCP server to Claude Code config
 */
function addToClaudeConfig(): boolean {
  const entry = getClaudeConfigEntry();

  // Check for install method change
  const existingMethod = getExistingInstallMethod();
  const currentMethod = isNpmInstall() ? "npm" : "source";

  if (existingMethod && existingMethod !== currentMethod) {
    p.log.info(`Updating Claude config from ${existingMethod} to ${currentMethod} installation`);
  }

  return writeClaudeConfig(entry);
}

/**
 * Generate config snippet for manual setup
 */
function getConfigSnippet(): string {
  const entry = getClaudeConfigEntry();
  return JSON.stringify({ "apple-notes": entry }, null, 2);
}

/**
 * Run indexing with specified mode
 */
async function runIndexing(mode: "full" | "incremental"): Promise<{ count: number; timeMs: number; skipped?: number }> {
  // Dynamic import to avoid loading embeddings before config is set
  const { indexNotes } = await import("./search/indexer.js");
  const result = await indexNotes(mode);
  return {
    count: result.indexed,
    timeMs: result.timeMs,
    skipped: result.breakdown?.skipped,
  };
}

/**
 * Download local model (warm up the pipeline)
 */
async function downloadLocalModel(): Promise<void> {
  const { getLocalEmbedding } = await import("./embeddings/local.js");
  // Generate a test embedding to trigger model download
  await getLocalEmbedding("test");
}

/**
 * Main setup wizard
 */
async function main(): Promise<void> {
  checkBunRuntime();
  console.clear();

  p.intro("apple-notes-mcp Setup Wizard");

  // Check existing configuration
  let existingEnv = readExistingEnv();
  const hasExistingConfig = Object.keys(existingEnv).length > 0;

  if (hasExistingConfig) {
    p.note(
      "Existing configuration found in .env\n" +
      "Your current settings will be shown as defaults.",
      "Configuration Detected"
    );
  }

  // Check for legacy config migration
  if (hasLegacyConfig() && !hasConfig()) {
    const migrate = await p.confirm({
      message: "Found config in project directory. Migrate to ~/.apple-notes-mcp/?",
      initialValue: true,
    });

    if (p.isCancel(migrate)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    if (migrate) {
      ensureConfigDir();
      fs.copyFileSync(getLegacyEnvPath(), getEnvPath());
      fs.chmodSync(getEnvPath(), 0o600);
      existingEnv = readExistingEnv();
      p.log.success("Config migrated to ~/.apple-notes-mcp/.env");
    }
  }

  // Provider selection
  const wasOpenRouter = Boolean(existingEnv.OPENROUTER_API_KEY);
  const provider = await p.select({
    message: "Which embedding provider would you like to use?",
    options: [
      {
        value: "local",
        label: "Local (HuggingFace)",
        hint: "Free, runs on your machine, ~200MB model download",
      },
      {
        value: "openrouter",
        label: "OpenRouter API",
        hint: "Fast, requires API key, pay-per-use",
      },
    ],
    initialValue: wasOpenRouter ? "openrouter" : "local",
  });

  if (p.isCancel(provider)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  let openrouterApiKey: string | undefined;
  let embeddingModel: string | undefined;
  let embeddingDims: number | undefined;

  if (provider === "openrouter") {
    const apiKey = await p.text({
      message: "Enter your OpenRouter API key:",
      placeholder: "sk-or-v1-...",
      initialValue: existingEnv.OPENROUTER_API_KEY || "",
      validate: (value) => {
        const key = value.trim();
        if (!key) return "API key is required";
        if (!key.startsWith("sk-or-")) return "Invalid API key format (should start with sk-or-)";
        if (/[\s"'`\\]/.test(key)) return "API key must not contain spaces, quotes or backslashes";
      },
    });

    if (p.isCancel(apiKey)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    openrouterApiKey = apiKey.trim();

    const existingCustomModel = wasOpenRouter ? existingEnv.EMBEDDING_MODEL : undefined;
    const useCustomModel = await p.confirm({
      message: `Use custom embedding model? (default: ${DEFAULT_OPENROUTER_MODEL})`,
      initialValue: Boolean(existingCustomModel),
    });

    if (p.isCancel(useCustomModel)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    if (useCustomModel) {
      const model = await p.text({
        message: "Enter model name:",
        placeholder: DEFAULT_OPENROUTER_MODEL,
        initialValue: existingCustomModel || DEFAULT_OPENROUTER_MODEL,
        validate: (value) => {
          if (!value.trim()) return "Model name is required";
          if (/[\r\n]/.test(value)) return "Model name must be a single line";
        },
      });

      if (p.isCancel(model)) {
        p.cancel("Setup cancelled.");
        process.exit(0);
      }

      embeddingModel = model.trim();

      const dims = await p.text({
        message: "Enter embedding dimensions:",
        placeholder: "4096",
        initialValue: (wasOpenRouter && existingEnv.EMBEDDING_DIMS) || "4096",
        validate: (value) => {
          if (!/^\d+$/.test(value.trim()) || Number(value) <= 0) return "Must be a positive integer";
        },
      });

      if (p.isCancel(dims)) {
        p.cancel("Setup cancelled.");
        process.exit(0);
      }

      embeddingDims = parseInt(dims.trim(), 10);
    }
  } else if (!wasOpenRouter) {
    // Staying local: keep a previously configured local model (e.g. Xenova/bge-m3)
    // so existing index dimensions stay valid. Switching from OpenRouter drops it.
    embeddingModel = existingEnv.EMBEDDING_MODEL;
  }

  // Read-only mode
  const readonlyMode = await p.confirm({
    message: "Enable read-only mode? (prevents all write operations to Apple Notes)",
    initialValue: parseFlag(existingEnv.READONLY_MODE),
  });

  if (p.isCancel(readonlyMode)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  // Auto-indexing
  const autoIndex = await p.select({
    message: "Auto-indexing mode:",
    options: [
      {
        value: "none",
        label: "Manual only",
        hint: "Run index-notes manually when needed",
      },
      {
        value: "ttl",
        label: "Time-based (TTL)",
        hint: "Auto-reindex after specified time",
      },
    ],
    initialValue: existingEnv.INDEX_TTL ? "ttl" : "none",
  });

  if (p.isCancel(autoIndex)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  let indexTtl: number | undefined;

  if (autoIndex === "ttl") {
    const ttl = await p.select({
      message: "Reindex after:",
      options: [
        { value: "3600", label: "1 hour" },
        { value: "21600", label: "6 hours" },
        { value: "86400", label: "24 hours" },
        { value: "604800", label: "1 week" },
      ],
      initialValue: existingEnv.INDEX_TTL || "86400",
    });

    if (p.isCancel(ttl)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    indexTtl = parseInt(ttl, 10);
  }

  // Debug mode
  const debug = await p.confirm({
    message: "Enable debug logging?",
    initialValue: parseFlag(existingEnv.DEBUG),
  });

  if (p.isCancel(debug)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  // Build configuration
  const config: Config = {
    provider: provider as "local" | "openrouter",
    openrouterApiKey,
    embeddingModel,
    embeddingDims,
    readonlyMode,
    autoIndex: autoIndex as "none" | "ttl",
    indexTtl,
    debug,
  };

  // Save configuration
  const s = p.spinner();

  s.start("Saving configuration...");
  writeEnvFile(config, existingEnv);
  // Load the config just written before anything reads it (model download,
  // indexing); it wins over values inherited from the shell.
  dotenv.config({ path: ENV_FILE, override: true, quiet: true });
  s.stop("Configuration saved to .env");

  // Download local model if needed
  if (provider === "local") {
    const downloadModel = await p.confirm({
      message: "Download local embedding model now? (~200MB, recommended)",
      initialValue: true,
    });

    if (p.isCancel(downloadModel)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    if (downloadModel) {
      s.start("Downloading embedding model (this may take a minute)...");
      try {
        await downloadLocalModel();
        s.stop("Model downloaded successfully");
      } catch (error) {
        s.stop("Model download failed (will download on first use)");
        p.log.warn(
          `Download error: ${error instanceof Error ? error.message : String(error)}`
        );
      }
    }
  }

  // Claude Code integration
  const addToClaude = await p.confirm({
    message: "Add to Claude Code configuration (~/.claude.json)?",
    initialValue: true,
  });

  if (p.isCancel(addToClaude)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  if (addToClaude) {
    s.start("Updating Claude Code configuration...");
    const success = addToClaudeConfig();
    if (success) {
      s.stop("Added to ~/.claude.json");
    } else {
      s.stop("Failed to update Claude config");
      p.log.warn("You may need to add the server manually.");
      p.note(getConfigSnippet(), "Add this to mcpServers in ~/.claude.json");
    }
  } else {
    p.note(getConfigSnippet(), "Add this to mcpServers in ~/.claude.json");
  }

  // Initial indexing
  const runIndex = await p.confirm({
    message: "Index your Apple Notes now?",
    initialValue: true,
  });

  if (p.isCancel(runIndex)) {
    p.cancel("Setup cancelled.");
    process.exit(0);
  }

  if (runIndex) {
    // Ask for indexing mode
    const indexMode = await p.select({
      message: "Indexing mode:",
      options: [
        { value: "incremental", label: "Incremental", hint: "Only new/changed notes (faster)" },
        { value: "full", label: "Full", hint: "Reindex everything (slower)" },
      ],
      initialValue: "incremental",
    });

    if (p.isCancel(indexMode)) {
      p.cancel("Setup cancelled.");
      process.exit(0);
    }

    const mode = indexMode as "full" | "incremental";
    const indexingMsg = `${mode === "full" ? "Full" : "Incremental"} indexing...`;

    // Don't use spinner in debug mode - it conflicts with debug output
    if (!debug) {
      s.start(indexingMsg);
    } else {
      p.log.info(indexingMsg);
    }

    try {
      const result = await runIndexing(mode);
      const skippedInfo = result.skipped ? `, ${result.skipped} unchanged` : "";
      const doneMsg = `Indexed ${result.count} notes in ${(result.timeMs / 1000).toFixed(1)}s${skippedInfo}`;

      if (!debug) {
        s.stop(doneMsg);
      } else {
        p.log.success(doneMsg);
      }
    } catch (error) {
      if (!debug) {
        s.stop("Indexing failed");
      }
      p.log.error(
        `Error: ${error instanceof Error ? error.message : String(error)}`
      );
      p.log.info("You can run indexing later with the index-notes tool.");
    }
  }

  // Summary
  p.note(
    [
      `Provider: ${provider === "local" ? "Local HuggingFace" : "OpenRouter"}`,
      `Read-only: ${readonlyMode ? "Yes" : "No"}`,
      `Auto-index: ${autoIndex === "ttl" ? `Every ${indexTtl! / 3600}h` : "Manual"}`,
      `Debug: ${debug ? "Enabled" : "Disabled"}`,
    ].join("\n"),
    "Configuration Summary"
  );

  p.outro("Setup complete! Restart Claude Code to use apple-notes-mcp.");
}

main().catch((error) => {
  console.error("Setup failed:", error);
  process.exit(1);
});
